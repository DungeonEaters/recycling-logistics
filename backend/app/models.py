import enum
import uuid
from datetime import date, datetime, timezone

from sqlalchemy import Boolean, Date, DateTime, Enum, Float, ForeignKey, Integer, String, Uuid
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .db import Base


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class Role(str, enum.Enum):
    admin = "admin"
    driver = "driver"


class RouteStatus(str, enum.Enum):
    planned = "planned"
    in_progress = "in_progress"
    completed = "completed"


class StopStatus(str, enum.Enum):
    pending = "pending"
    visited = "visited"
    skipped = "skipped"


class User(Base):
    __tablename__ = "users"
    id: Mapped[int] = mapped_column(primary_key=True)
    email: Mapped[str] = mapped_column(String(255), unique=True, index=True)
    name: Mapped[str] = mapped_column(String(120))
    password_hash: Mapped[str] = mapped_column(String(255))
    role: Mapped[Role] = mapped_column(Enum(Role))
    active: Mapped[bool] = mapped_column(Boolean, default=True)


class Client(Base):
    __tablename__ = "clients"
    id: Mapped[int] = mapped_column(primary_key=True)
    name: Mapped[str] = mapped_column(String(160))
    kind: Mapped[str] = mapped_column(String(40), default="company")  # company | condominium | other
    tax_id: Mapped[str | None] = mapped_column(String(40), nullable=True)
    contact_name: Mapped[str | None] = mapped_column(String(120), nullable=True)
    contact_phone: Mapped[str | None] = mapped_column(String(40), nullable=True)
    active: Mapped[bool] = mapped_column(Boolean, default=True)
    points: Mapped[list["CollectionPoint"]] = relationship(back_populates="client")


class CollectionPoint(Base):
    __tablename__ = "collection_points"
    id: Mapped[int] = mapped_column(primary_key=True)
    client_id: Mapped[int] = mapped_column(ForeignKey("clients.id"))
    name: Mapped[str] = mapped_column(String(160))
    address: Mapped[str] = mapped_column(String(255), default="")
    lat: Mapped[float] = mapped_column(Float)
    lng: Mapped[float] = mapped_column(Float)
    notes: Mapped[str | None] = mapped_column(String(500), nullable=True)
    active: Mapped[bool] = mapped_column(Boolean, default=True)
    client: Mapped[Client] = relationship(back_populates="points")


class Truck(Base):
    __tablename__ = "trucks"
    id: Mapped[int] = mapped_column(primary_key=True)
    plate: Mapped[str] = mapped_column(String(20), unique=True)
    name: Mapped[str] = mapped_column(String(80), default="")
    capacity_kg: Mapped[float | None] = mapped_column(Float, nullable=True)
    active: Mapped[bool] = mapped_column(Boolean, default=True)


class Route(Base):
    __tablename__ = "routes"
    id: Mapped[int] = mapped_column(primary_key=True)
    date: Mapped[date] = mapped_column(Date, index=True)
    truck_id: Mapped[int | None] = mapped_column(ForeignKey("trucks.id"), nullable=True)
    driver_id: Mapped[int | None] = mapped_column(ForeignKey("users.id"), nullable=True)
    status: Mapped[RouteStatus] = mapped_column(Enum(RouteStatus), default=RouteStatus.planned)
    optimizer: Mapped[str] = mapped_column(String(40), default="none")
    origin_lat: Mapped[float | None] = mapped_column(Float, nullable=True)
    origin_lng: Mapped[float | None] = mapped_column(Float, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    truck: Mapped[Truck | None] = relationship()
    driver: Mapped[User | None] = relationship()
    stops: Mapped[list["RouteStop"]] = relationship(
        back_populates="route", order_by="RouteStop.sequence", cascade="all, delete-orphan"
    )


class RouteStop(Base):
    __tablename__ = "route_stops"
    id: Mapped[int] = mapped_column(primary_key=True)
    route_id: Mapped[int] = mapped_column(ForeignKey("routes.id"))
    point_id: Mapped[int] = mapped_column(ForeignKey("collection_points.id"))
    sequence: Mapped[int] = mapped_column(Integer)
    status: Mapped[StopStatus] = mapped_column(Enum(StopStatus), default=StopStatus.pending)
    visited_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    route: Mapped[Route] = relationship(back_populates="stops")
    point: Mapped[CollectionPoint] = relationship()


class Weighing(Base):
    """Id is generated by the client so offline retries are idempotent."""

    __tablename__ = "weighings"
    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True)
    stop_id: Mapped[int] = mapped_column(ForeignKey("route_stops.id"))
    route_id: Mapped[int] = mapped_column(ForeignKey("routes.id"), index=True)
    point_id: Mapped[int] = mapped_column(ForeignKey("collection_points.id"))
    driver_id: Mapped[int] = mapped_column(ForeignKey("users.id"))
    kg: Mapped[float] = mapped_column(Float)
    material: Mapped[str] = mapped_column(String(40), default="plastico")
    notes: Mapped[str | None] = mapped_column(String(500), nullable=True)
    weighed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    received_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    stop: Mapped[RouteStop] = relationship()
    point: Mapped[CollectionPoint] = relationship()
    route: Mapped[Route] = relationship()
    driver: Mapped[User] = relationship()
